const mongoose = require('mongoose');

const foodCategorySchema = new mongoose.Schema(
  {
    restaurant: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Restaurant',
      required: true,
      index: true,
    },
    name: {
      type: String,
      required: [true, 'Category name is required'],
      trim: true,
    },
    description: {
      type: String,
      trim: true,
      default: '',
    },
    image: {
      type: String,
      default: '',
    },
    isActive: {
      type: Boolean,
      default: true,
    },
  },
  { timestamps: true }
);

// Prevent the same restaurant from creating two categories with the same name.
foodCategorySchema.index({ restaurant: 1, name: 1 }, { unique: true });

module.exports = mongoose.model('FoodCategory', foodCategorySchema);
